public class P3향상된for문 {
    public static void main(String[] args) {
        //배열(ch5)에서 본격적으로 나옴. 맛보기만 보자
        int[] nums = {1, 2, 3};
        for (int n : nums) {          //nums의 요소를 하나씩 꺼내서 n에 담아줌
            System.out.println(n);
        }
        //간결하지만 인덱스(몇 번째인지)가 필요하면 기본 for문을 쓰자
    }
}
